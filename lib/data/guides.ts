/**
 * Image guides content center (AdSense "content site" substance + organic
 * search surface). Each guide is a long-form, illustrated article that lives
 * at `/guides/[slug]`.
 *
 * Content is authored in English only for now. It lives here as typed data
 * (not in the next-intl message catalog) so the message files stay manageable
 * and a future translation pass can migrate it locale-by-locale. The page
 * chrome (index hero, "read article", reading-time label, related-tools
 * heading, etc.) IS localized — see the `Guides` namespace in messages.
 *
 * Each article is "图文并茂": one SVG concept diagram (the cover, reused inline)
 * plus, where it helps, a real raster demonstration image generated by
 * `scripts/generate-guide-assets.py` into `public/guides/`.
 */

/** Broad topic bucket shown as a label on cards + article meta. */
export type GuideCategory =
  | "Formats"
  | "Compression"
  | "Resolution"
  | "Metadata"
  | "Editing"
  | "Color"
  | "Privacy";

/**
 * Registry of SVG concept diagrams rendered by
 * `components/guides/guide-diagram.tsx`. A guide references one by name as its
 * `coverDiagram` and may embed it inline in its body. Add a name here AND a
 * matching component in the diagram registry when introducing a new diagram.
 */
export type DiagramName =
  | "format-support-table"
  | "compression-flow"
  | "ppi-vs-dpi"
  | "exif-rotation"
  | "aspect-ratio-boxes"
  | "quality-size-curve"
  | "bit-depth-gradient"
  | "alpha-channel"
  | "resize-vs-crop"
  | "meme-layout"
  | "watermark-types"
  | "blur-vs-pixelate";

/**
 * A single block of article body content. The renderer
 * (`components/guides/guide-body.tsx`) switches on `type`. Keeping bodies as a
 * flat block list makes authoring + future translation straightforward.
 */
export type Block =
  | { type: "heading"; text: string }
  | { type: "paragraph"; text: string }
  | { type: "list"; items: string[] }
  | { type: "callout"; text: string }
  | { type: "diagram"; name: DiagramName; caption?: string }
  | {
      type: "image";
      src: string;
      alt: string;
      width: number;
      height: number;
      caption?: string;
    };

export interface Guide {
  slug: string;
  title: string;
  description: string;
  category: GuideCategory;
  /** SVG diagram shown as the card cover + article hero (fallback when no coverImage). */
  coverDiagram: DiagramName;
  /**
   * Raster cover image generated via wan2.7-image-pro at
   * `/guides/<slug>-cover.webp`. Rendered as the card cover + article hero when
   * present; falls back to `coverDiagram`. See `scripts/generate-guide-covers.py`.
   */
  coverImage?: string;
  readingTimeMin: number;
  /** Slugs of tools to link from the article footer (resolved via lib/data/tools). */
  relatedToolSlugs: string[];
  /** ISO date for the "published" meta + article ordering (newest first in index). */
  publishedAt: string;
  body: Block[];
}

